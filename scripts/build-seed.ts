/**
 * Generates supabase/seed.sql from src/content/seed (single source of truth for initial content).
 * Idempotent: rows are only inserted when missing, so re-running never overwrites edits made in the panel.
 * Run: npm run seed:build
 */
import { writeFileSync } from "node:fs";
import * as seed from "../src/content/seed";

const DQ = "$" + "j" + "$";
const SQ = "$" + "s" + "$";
const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) && v.length && v.every((x) => typeof x === "string")) return `array[${v.map((x) => q(x)).join(",")}]::text[]`;
  if (Array.isArray(v) && v.length === 0) return "'{}'";
  if (typeof v === "object") return `${DQ}${JSON.stringify(v)}${DQ}::jsonb`;
  if (typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v)) return `${SQ}${v}${SQ}::date`;
  return `${SQ}${String(v)}${SQ}`;
};

function insert(table: string, rows: Record<string, unknown>[], conflict: string | null) {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]!).map((k) => `"${k}"`).join(", ");
  const keys = Object.keys(rows[0]!);
  const values = rows.map((r) => `(${keys.map((k) => q(r[k])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols}) values\n${values}${conflict ? `\non conflict (${conflict}) do nothing` : ""};\n`;
}
/** For tables without a natural key: seed only when the table is empty. */
function insertIfEmpty(table: string, rows: Record<string, unknown>[]) {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]!).map((k) => `"${k}"`).join(", ");
  const keys = Object.keys(rows[0]!);
  const values = rows.map((r) => `(${keys.map((k) => q(r[k])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols})\nselect * from (values\n${values}\n) v where not exists (select 1 from public.${table});\n`;
}

const strip = <T extends { id?: string }>(xs: T[]) => xs.map(({ id: _id, ...rest }) => rest as Record<string, unknown>);

const parts: string[] = ["-- Generated by scripts/build-seed.ts — do not edit by hand.\n"];
parts.push(insert("languages", seed.languages as unknown as Record<string, unknown>[], "code"));
parts.push(
  insert(
    "settings",
    [
      { key: "site", value: seed.settings },
      { key: "tracking", value: seed.tracking },
      { key: "services_also_offered", value: seed.servicesAlsoOffered },
    ],
    "key",
  ),
);
parts.push(insert("ui_strings", Object.entries(seed.ui).map(([key, values]) => ({ key, values })), "key"));
parts.push(insert("menus", seed.menus.map((m) => ({ location: m.location, items: m.items })), "location"));
parts.push(
  insert(
    "pages",
    seed.pages.map((p) => ({ slug: p.slug, kind: p.kind, published: p.published, title: p.title, seo: p.seo, blocks: p.blocks, published_at: new Date().toISOString() })),
    "slug",
  ),
);
parts.push(insert("services", strip(seed.services), "slug"));
parts.push(insert("team_members", strip(seed.team), "slug"));
parts.push(insertIfEmpty("clients", strip(seed.clients)));
parts.push(insertIfEmpty("certificates", strip(seed.certificates)));
parts.push(insertIfEmpty("branches", strip(seed.branches)));
parts.push(insertIfEmpty("faqs", strip(seed.faqs)));
parts.push(insertIfEmpty("gallery_items", strip(seed.gallery)));
parts.push(
  insert(
    "post_categories",
    [
      { slug: "tax", name: { ar: "الضرائب", en: "Tax" } },
      { slug: "audit", name: { ar: "المراجعة", en: "Audit" } },
      { slug: "accounting", name: { ar: "المحاسبة", en: "Accounting" } },
      { slug: "corporate", name: { ar: "شؤون الشركات", en: "Corporate affairs" } },
    ],
    "slug",
  ),
);
parts.push(insert("authors", [{ slug: "mahmoud-al-sheikh", name: seed.team[0]!.name, bio: seed.team[0]!.role, team_slug: "mahmoud-al-sheikh" }], "slug"));

const sql = parts.join("\n");
writeFileSync("supabase/seed.sql", sql);
console.log(`supabase/seed.sql written (${sql.length} bytes)`);
